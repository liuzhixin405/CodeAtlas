    [Fact]
    public void IsGeneratedSource_HeaderMarkerAfterLicense()
    {
        // 许可证头 14 行之后才有生成标记（microservices-demo 的 genproto 就这样）；文件名不带 .pb.go 也要认
        var lines = Enumerable.Range(1, 14).Select(i => $"// Copyright line {i}").Append("// Code generated by protoc-gen-go. DO NOT EDIT.").Append("package genproto").ToList();
        Assert.True(ProjectInventory.IsGeneratedSource("src/shop/genproto/demo.go", lines));
        Assert.True(ProjectInventory.IsGeneratedSource("Shop.Api/Proto/Cart.cs", ["// <auto-generated>", "//     Generated by the protocol buffer compiler.  DO NOT EDIT!", "// </auto-generated>"]));
        // 前 40 行之外的不算；普通注释里提到 generated 不算
        var late = Enumerable.Range(1, 40).Select(i => "// x").Append("// Code generated by hand. DO NOT EDIT.").ToList();
        Assert.False(ProjectInventory.IsGeneratedSource("src/shop/late.go", late));
        Assert.False(ProjectInventory.IsGeneratedSource("src/shop/doc.go", ["// This file is not generated; edit freely.", "package shop"]));
    }

    [Fact]
    public void Hot_CommitsAreDistinctAcrossFiles_RevisionsStayTheFileSum()
    {
        // 两个文件被同一次提交 a1 改过：文件修订合计 3 + 2 = 5，涉及的提交是 a1 a2 a3 b1 = 4 次
        var log = string.Join('\n',
            "--a1--2026-09-01--Ann", "1\t0\tAcme.App/Orders/Svc.cs", "1\t0\tAcme.App/Users/Svc.cs",
            "--a2--2026-09-02--Ann", "1\t0\tAcme.App/Orders/Svc.cs",
            "--a3--2026-09-03--Bob", "1\t0\tAcme.App/Orders/Svc.cs",
            "--b1--2026-09-04--Bob", "1\t0\tAcme.App/Users/Svc.cs");
        var git = GitHistory.Parse(log);
        Assert.Equal(["a1", "a2", "a3"], git.Files.Single(f => f.Path == "Acme.App/Orders/Svc.cs").Commits!);
        var d = DsmBuilder.Build(Symbols, Edges, Api, "", git, new DateOnly(2026, 10, 1));
        var app = d.Components.Single(c => c.Key == "Acme.App").Hot!;
        Assert.Equal((5, 4), (app.Revisions, app.Commits));

        // 从库里读回的统计没有提交号：Commits 为 null（页面写"文件修订合计"）
        var stored = new GitHistoryResult(git.Files.Select(f => f with { Commits = null }).ToList(), [], 4, 0, null);
        Assert.Null(DsmBuilder.Build(Symbols, Edges, Api, "", stored, new DateOnly(2026, 10, 1)).Components.Single(c => c.Key == "Acme.App").Hot!.Commits);
    }
