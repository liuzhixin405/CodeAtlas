    [Fact]
    public void RepoContainer_SkipsProjectsUnderTestTrees()
    {
        var root = Path.Combine(Path.GetTempPath(), "codeatlas-lib-" + Guid.NewGuid().ToString("N"));
        try
        {
            void Write(string rel, string content)
            {
                var full = Path.Combine(root, rel.Replace('/', Path.DirectorySeparatorChar));
                Directory.CreateDirectory(Path.GetDirectoryName(full)!);
                File.WriteAllText(full, content);
            }
            Write("src/Shop.Core/Shop.Core.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>");
            // 测试夹具：测试树下的 csproj（不带测试包）、Go 模块、Python 项目、前端
            Write("tests/Shop.Core.Tests/Fixtures/Sample/Sample.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>");
            Write("tests/Shop.Core.Tests/Fixtures/go/go.mod", "module example.com/fixture\n");
            Write("tests/Shop.Core.Tests/Fixtures/go/main.go", "package main\nfunc main() {}\n");
            Write("test/fixtures/py/pyproject.toml", "[project]\nname = \"fixture\"\n");
            Write("src/Shop.Web/__tests__/app/package.json", """{ "name": "fx", "scripts": { "build": "vite build" }, "dependencies": { "vite": "5" } }""");
            Write("src/Shop.Web/package.json", """{ "name": "shop-web", "scripts": { "build": "vite build" }, "dependencies": { "vite": "5" } }""");

            var repo = DsmBuilder.RepoContainer(ProjectRoots.Single(root));
            Assert.Equal(["src/Shop.Core", "src/Shop.Web"], repo.Members);
        }
        finally
        {
            if (Directory.Exists(root)) Directory.Delete(root, recursive: true);
        }
    }

    [Fact]
    public void GeneratedCode_IsNotAComponent()
    {
        List<MapSymbol> symbols =
        [
            Sym(4001, SymbolKind.Function, "src/checkout.main", "src/checkout/main.go"),
            Sym(4002, SymbolKind.Function, "src/checkout/money.Sum", "src/checkout/money/money.go"),
            Sym(4010, SymbolKind.Class, "src/checkout/genproto.CartItem", "src/checkout/genproto/demo.pb.go"),
            Sym(4011, SymbolKind.Function, "src/checkout/genproto.NewCartServiceClient", "src/checkout/genproto/demo_grpc.pb.go"),
            Sym(4020, SymbolKind.Class, "src/checkout.demo_pb2_grpc.CartStub", "src/checkout/demo_pb2_grpc.py"),
        ];
        List<MapEdge> edges = [new(4001, 4002, EdgeKind.Calls), new(4001, 4011, EdgeKind.Calls), new(4002, 4010, EdgeKind.References)];
        var c = new ArchNode("src/checkout", ArchNodeKind.Container, "go-service", "checkout", "src/checkout", ArchSource.Discovered, [], ["src/checkout"], []);
        var d = DsmBuilder.Build(symbols, edges, c, "", null);
        Assert.Equal(new[] { ("src/checkout/money", 1, 1), ("src/checkout", 1, 1) }, d.Components.Select(x => (x.Key, x.Symbols, x.Files)));
        Assert.Equal((1, 0, 1), (d.Cells.Single().Row, d.Cells.Single().Col, d.Cells.Single().Count));
    }

